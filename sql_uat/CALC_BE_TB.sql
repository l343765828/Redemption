  -- 对碰计奖基数
	INSERT INTO AR_CALC_BE_TB_MID2
	SELECT T.PERIOD_NUM,
	       T.CALC_MONTH,
	       T.USER_ID,
				 T.TOTAL_1L,-- 1市场总业绩
				 T.TOTAL_2L,-- 2市场总业绩
				 T.SURPLUS_1L,-- 1市场结余业绩
				 T.SURPLUS_2L,-- 2市场结余业绩
				 T.TOUCH_PV,-- 对碰业绩
				 T.LAST_MEMBER_LV,-- 用户Member级别
				 T.LAST_MEMBER_CALC_ID,-- 级别对应的序号
				 T.TOUCH_RATE,-- 对碰比例
				 T.TOUCH_CAPPING,-- 对碰封顶
				 T.TOUCH_PV * T.TOUCH_RATE AS ORI_TOUCH_BASE,-- 封顶前对碰基数
				 CASE WHEN T.TOUCH_CAPPING = 0 THEN T.TOUCH_PV * T.TOUCH_RATE
				      WHEN T.TOUCH_CAPPING <= T.TOUCH_PV * T.TOUCH_RATE THEN T.TOUCH_CAPPING
							ELSE T.TOUCH_PV * T.TOUCH_RATE END AS TOUCH_BASE, -- 封顶后对碰基数
				 T.IS_ACTIVE -- 是否活跃
	  FROM AR_CALC_BE_TB_MID1 T
	 WHERE T.TOUCH_PV > 0;
	COMMIT;
	--
	SELECT IFNULL(SUM(PV_PCS),0) INTO VV_TOTAL_PV FROM AR_PERF_MONTH T WHERE T.PERIOD_NUM = IV_PERIOD_NUM;
	--
	SELECT IFNULL(SUM(T.TOUCH_BASE),0) INTO VV_TOTAL_BASE FROM AR_CALC_BE_TB_MID2 T WHERE T.IS_ACTIVE = 1;

	SELECT IFNULL(MIN(T.VALUE),0)/100 INTO VV_TB_BISECT_RATE FROM AR_CONFIG T WHERE T.CONFIG_NAME = 'teamBisectRate' AND T.TYPE = 'bonus';

	-- 团队奖总奖金
	SET VV_TOTAL_TB = VV_TOTAL_PV * VV_TB_BISECT_RATE;
	-- 比例
	SET VV_TB_RATE = CASE WHEN VV_TOTAL_BASE = 0 THEN 0 ELSE TRUNCATE(VV_TOTAL_TB/VV_TOTAL_BASE,6) END;

-- 	INSERT INTO AR_CALC_BE_LOG(CALC_ID,TEXT,CREATE_TIME) VALUES (0,'3',NOW());
-- 	COMMIT;
	SET VV_TIME_STR = DATE_FORMAT(NOW(),'%Y%m%d%H%i%s');
	-- 团队奖
	IF(VV_TB_RATE > 0) THEN
	  INSERT INTO AR_CALC_BONUS_TB
		SELECT CONCAT(VV_TIME_STR,LPAD(@ROWNUM:=@ROWNUM+1,8,'0')) AS ID,-- 年月日时分秒14+排序8
					 T.PERIOD_NUM,
					 T.CALC_MONTH,
					 T.USER_ID,
					 T.TOTAL_1L,-- 1市场总业绩
					 T.TOTAL_2L,-- 2市场总业绩
					 T.SURPLUS_1L,-- 1市场结余业绩
					 T.SURPLUS_2L,-- 2市场结余业绩
					 T.TOUCH_PV,-- 对碰业绩
					 T.LAST_MEMBER_LV,-- 用户Member级别
					 T.LAST_MEMBER_CALC_ID,-- 级别对应的序号
					 T.TOUCH_RATE,-- 对碰比例
					 T.TOUCH_CAPPING,-- 对碰封顶
					 T.ORI_TOUCH_BASE,-- 封顶前对碰基数
					 T.TOUCH_BASE,-- 封顶后对碰基数
					 VV_TB_RATE AS TB_RATE,-- 比例
					 TRUNCATE(T.TOUCH_BASE * VV_TB_RATE,2) AS BONUS_TB,-- 团队奖
					 IFNULL(T1.COUNTRY_ID,'-1') AS COUNTRY_ID,
					 T.IS_ACTIVE
			FROM (SELECT @ROWNUM := 0 FROM DUAL) R,AR_CALC_BE_TB_MID2 T
			LEFT JOIN AR_USER T1 ON T1.ID = T.USER_ID
		 WHERE T.TOUCH_BASE > 0
		   AND T.IS_ACTIVE = 1;
		COMMIT;
	END IF;


