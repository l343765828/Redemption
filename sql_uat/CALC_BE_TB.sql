  DECLARE VV_TOTAL_PV,
	        VV_TOTAL_BASE,
					VV_TOTAL_TB,
					VV_TB_RATE,
					VV_TB_BISECT_RATE
	DECIMAL(16,6);
	DECLARE VV_TIME_STR,-- 当前时间的年月日时分秒数字
	        VV_USER_ID,
					VV_PARENT_UID
	  VARCHAR(32);

	DECLARE VV_COUNT,
	        VV_TOP_DEEP
	  INT;
	/*--------------------------------------------表说明--------------------------------------------*/
	/*
	  AR_CALC_BE_TB_MID1：会员的级别，对碰比例，封顶等信息
	  AR_CALC_BE_TB_MID2：对碰计奖基数
		AR_CALC_BE_TB_MID3：会员左右市场的会员数和总业绩信息
	*/
-- 	INSERT INTO AR_CALC_BE_LOG(CALC_ID,TEXT,CREATE_TIME) VALUES (0,'1',NOW());
-- 	COMMIT;
	-- 会员的级别，对碰比例，封顶等信息
	INSERT INTO AR_CALC_BE_TB_MID1
	SELECT T.PERIOD_NUM,
	       T.CALC_MONTH,
	       T.USER_ID,
				 T.TOTAL_1L,-- 1市场总业绩
				 T.TOTAL_2L,-- 2市场总业绩
				 CASE WHEN T.TOTAL_1L - T.TOTAL_2L >= 0 THEN T.TOTAL_1L - T.TOTAL_2L ELSE 0 END AS SURPLUS_1L,-- 1市场结余业绩
				 CASE WHEN T.TOTAL_2L - T.TOTAL_1L > 0 THEN T.TOTAL_2L - T.TOTAL_1L ELSE 0 END AS SURPLUS_2L,-- 2市场结余业绩
				 CASE WHEN T.TOTAL_1L - T.TOTAL_2L >= 0 THEN T.TOTAL_2L ELSE T.TOTAL_1L END AS TOUCH_PV,-- 对碰业绩
				 T1.MEMBER_LV AS LAST_MEMBER_LV,-- 用户Member级别
				 T2.CALC_ID AS LAST_MEMBER_CALC_ID,-- 级别对应的序号
				 IFNULL(T3.VALUE,0)/100 AS TOUCH_RATE,-- 对碰比例
				 IFNULL(T4.VALUE,0) AS TOUCH_CAPPING, -- 对碰封顶
				 T.IS_ACTIVE -- 是否活跃
	  FROM AR_PERF_MONTH T
		LEFT JOIN AR_USER T1 ON T1.ID = T.USER_ID
		LEFT JOIN AR_MEMBER_LEVEL T2 ON T2.ID = T1.MEMBER_LV
		LEFT JOIN AR_CONFIG T3 ON T3.CONFIG_NAME = CONCAT('teamTouchRate',T2.CALC_ID) AND T3.TYPE = 'bonus'
		LEFT JOIN AR_CONFIG T4 ON T4.CONFIG_NAME = CONCAT('teamTouchCapping',T2.CALC_ID) AND T4.TYPE = 'bonus'
	 WHERE T.PERIOD_NUM = IV_PERIOD_NUM;
  COMMIT;

-- 	INSERT INTO AR_CALC_BE_LOG(CALC_ID,TEXT,CREATE_TIME) VALUES (0,'2',NOW());
